import os
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

import cli_reference  # noqa: E402

FIXTURE = '''
import argparse, os

def main(argv=None):
    parser = argparse.ArgumentParser(description="Fixture tool.")
    parser.add_argument("--home", default=os.environ.get("FIXTURE_HOME"), help="a|b for <x>")
    sub = parser.add_subparsers(dest="command", required=True)
    job = sub.add_parser("job", help="manage jobs")
    actions = job.add_subparsers(dest="action", required=True)
    add = actions.add_parser("add")
    add.add_argument("name")
    add.add_argument("--kind", choices=("fast", "slow"), default="fast", help="how it runs")
    add.add_argument("--cwd", default=os.getcwd())
    add.add_argument("--retries", type=int, default=0)
    add.add_argument("--tag", action="append", default=[])
    add.add_argument("--quiet", action="store_true")
    parser.parse_args(argv)
'''

